"""Generates the script that prepares another Proxmox node to be managed by this dashboard.

The script is self-contained: it carries the matching gate (base64) and the dashboard's public key, so the node does
not download anything and the gate is always the same version as the dashboard. It is meant to be read, then run as
root on the new node."""
import base64
import ipaddress
import re
import textwrap
import time

PUBKEY_RE = re.compile(r"^ssh-ed25519 [A-Za-z0-9+/]{40,}={0,2}( [\w@.+-]{1,60})?$")
GATE_PATH = "/usr/local/sbin/updatedash-gate"
GATE_USER = "updatedash-gate"


class SetupError(ValueError):
    pass


def _ids(text):
    out = []
    for tok in re.split(r"[\s,]+", text or ""):
        if not tok:
            continue
        if not (tok.isdigit() and len(tok) <= 9):
            raise SetupError(f"not a CT id: {tok!r}")
        out.append(tok)
    return out


def build_setup_script(gate_source, pubkey, dashboard_ips=(), allow_ctids="", protected_ctids="", manage=True, gate_user=GATE_USER):
    pubkey = (pubkey or "").strip()
    if not PUBKEY_RE.match(pubkey):
        raise SetupError("the dashboard's public key is missing or not an ed25519 key")
    ips = []
    for ip in dashboard_ips or ():
        try:
            ips.append(str(ipaddress.ip_address(str(ip).strip())))
        except ValueError:
            raise SetupError(f"not an IP address: {ip!r}")
    if not re.match(r"^[a-z_][a-z0-9_-]{0,31}$", gate_user or ""):
        raise SetupError("bad gate user name")
    allow, protected = _ids(allow_ctids), _ids(protected_ctids)
    home = "/root" if gate_user == "root" else f"/var/lib/{gate_user}"
    cmd = GATE_PATH if gate_user == "root" else f"sudo -n {GATE_PATH}"
    b64 = "\n".join(textwrap.wrap(base64.b64encode(gate_source).decode(), 76))
    from_opt = f'from=\\"{",".join(ips)}\\",' if ips else ""      # the backslashes survive into bash's double quotes
    no_from_note = "" if ips else (
        "# WARNING: no dashboard IP was given, so this key is not restricted to one source address.\n")
    return f'''#!/usr/bin/env bash
# updatedash: prepare THIS Proxmox node to be managed by the dashboard.
# Generated by the dashboard on {time.strftime("%Y-%m-%d %H:%M:%S")}. Read it before you run it. It changes only:
#   {GATE_PATH}                    the restricted command the dashboard's key may run
#   /etc/updatedash-gate.allow|protected|commands|manage     which containers it may touch
#   user "{gate_user}"                 an unprivileged account with no password; it can only run the gate, as root, through sudo
#   /etc/sudoers.d/updatedash-gate       that one sudo rule (checked with visudo before it is installed)
#   {home}/.ssh/authorized_keys          one line for the dashboard's key (replaced if it already exists; root-owned)
# Re-run it any time; it is safe to repeat. To undo: userdel {gate_user}; delete the files above.
set -euo pipefail
R="${{UD_ROOT:-}}"
[ -n "$R" ] || {{ [ "$(id -u)" = 0 ] || {{ echo "Run as root." >&2; exit 1; }}; command -v pct >/dev/null || {{ echo "This is not a Proxmox node (no pct)." >&2; exit 1; }}; }}

ALLOW_CTIDS="${{ALLOW_CTIDS-{" ".join(allow)}}}"             # containers the dashboard may update (CT numbers on this node)
PROTECTED_CTIDS="${{PROTECTED_CTIDS-{" ".join(protected)}}}"  # containers the web UI may never add or remove
GUI_MANAGE="${{GUI_MANAGE-{1 if manage else 0}}}"              # 1 = the web UI may add/remove containers from the allow list
PUB='{pubkey}'
{no_from_note}
for id in $ALLOW_CTIDS $PROTECTED_CTIDS; do [[ "$id" =~ ^[0-9]+$ ]] || {{ echo "Bad CT id: $id" >&2; exit 1; }}; done

GATE_USER='{gate_user}'
GATE_HOME='{home}'
mkdir -p "$R/usr/local/sbin" "$R/etc" "$R$GATE_HOME/.ssh"
if [ "$GATE_USER" != root ] && [ -z "$R" ]; then
  command -v sudo >/dev/null 2>&1 || {{ echo "Installing sudo..."; apt-get install -y sudo >/dev/null; }}
  id "$GATE_USER" >/dev/null 2>&1 || useradd --system --home-dir "$GATE_HOME" --shell /bin/sh "$GATE_USER"
  usermod -p '*' "$GATE_USER"
  chown root:root "$GATE_HOME" "$GATE_HOME/.ssh"; chmod 755 "$GATE_HOME" "$GATE_HOME/.ssh"
fi
if [ "$GATE_USER" != root ]; then
  mkdir -p "$R/etc/sudoers.d"
  SUDO_TMP="$(mktemp)"
  printf '%s\n' 'Defaults!{GATE_PATH} env_keep += "SSH_ORIGINAL_COMMAND SSH_CONNECTION SSH_CLIENT"' \
    "$GATE_USER ALL=(root) NOPASSWD: {GATE_PATH}" > "$SUDO_TMP"
  if [ -z "$R" ]; then visudo -cf "$SUDO_TMP" >/dev/null || {{ echo "sudoers rule did not validate; stopping." >&2; exit 1; }}; fi
  install -m 0440 "$SUDO_TMP" "$R/etc/sudoers.d/updatedash-gate"; rm -f "$SUDO_TMP"
fi
base64 -d > "$R{GATE_PATH}" <<'UPDATEDASH_GATE_B64'
{b64}
UPDATEDASH_GATE_B64
chmod 755 "$R{GATE_PATH}"

touch "$R/etc/updatedash-gate.allow"
for id in $ALLOW_CTIDS; do grep -qx "$id" "$R/etc/updatedash-gate.allow" || echo "$id" >> "$R/etc/updatedash-gate.allow"; done
{{ echo "# CT ids the dashboard can never add or remove"; for id in $PROTECTED_CTIDS; do echo "$id"; done; }} > "$R/etc/updatedash-gate.protected"
[ -f "$R/etc/updatedash-gate.commands" ] || echo "# Extra commands the dashboard may run inside allowed containers, one exact command per line." > "$R/etc/updatedash-gate.commands"
if [ "$GUI_MANAGE" = 1 ]; then echo 0 > "$R/etc/updatedash-gate.manage"; else rm -f "$R/etc/updatedash-gate.manage"; fi

KEYBLOB="$(echo "$PUB" | awk '{{print $2}}')"
LINE="command=\\"{cmd}\\",{from_opt}restrict $PUB"
AK="$R$GATE_HOME/.ssh/authorized_keys"
touch "$AK"
TMP="$(mktemp)"
{{ grep -vF "$KEYBLOB" "$AK" || true; echo "$LINE"; }} > "$TMP"
cat "$TMP" > "$AK"
rm -f "$TMP"
if [ "$GATE_USER" != root ]; then chmod 644 "$AK"; [ -n "$R" ] || chown root:root "$AK"; fi

echo "Done. This node now accepts the dashboard's key, as user $GATE_USER, for the gate only."
echo "Allowed containers: $(grep -v '^#' "$R/etc/updatedash-gate.allow" | tr '\\n' ' ')"
echo "Next: back in the dashboard, check this node's SSH host key, confirm it, and add the node."
'''
